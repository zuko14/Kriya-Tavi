// S-2 (docs/kriya-harness/INSTALLER.md): copies the installer from the
// kriya-harness repository, which owns it, into lib/harness/install-script.ts
// with its sha256, so GET /install.sh serves exactly that file.
//   npx tsx scripts/harness-install-script.ts [../kriya-harness/install.sh]
import { createHash } from "node:crypto"
import fs from "node:fs"
import path from "node:path"

const source = path.resolve(
  process.argv[2] ?? path.join("..", "kriya-harness", "install.sh")
)
const text = fs.readFileSync(source, "utf8")
const sha = createHash("sha256").update(text).digest("hex")
const out = path.join(process.cwd(), "lib", "harness", "install-script.ts")
fs.writeFileSync(
  out,
  `// Generated by scripts/harness-install-script.ts from kriya-harness install.sh. Don't edit.
export const INSTALL_SCRIPT_SHA256 = "${sha}"

export const INSTALL_SCRIPT = ${JSON.stringify(text)}
`
)
console.log(`wrote lib/harness/install-script.ts (sha256 ${sha})`)
